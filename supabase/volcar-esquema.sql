-- Arma, sólo leyendo el catálogo, el DDL de los esquemas `public` y `privado`
-- de la base linkeada: extensiones, tipos, funciones, tablas, restricciones,
-- índices, vistas, disparadores, RLS, políticas, permisos y tareas de pg_cron.
-- Lo usa `node scripts/volcar-esquema.mjs`, que escribe el resultado en
-- `supabase/esquema-produccion.sql`. Existe porque no hay Docker ni pg_dump en
-- la máquina de desarrollo (`supabase db dump` necesita Docker).
with
ns as (
  select n.oid, n.nspname::text as nspname
    from pg_namespace n
   where n.nspname in ('public', 'privado')
),
extensiones as (
  select 10 as orden, e.extname::text as clave,
         format('create extension if not exists %I with schema %I;', e.extname, n.nspname) as ddl
    from pg_extension e
    join pg_namespace n on n.oid = e.extnamespace
   where e.extname <> 'plpgsql'
),
esquemas as (
  select 20, nspname, format('create schema if not exists %I;', nspname)
    from ns
   where nspname <> 'public'
),
tipos as (
  select 30, t.typname::text,
         format('create type %I.%I as enum (%s);', n.nspname, t.typname,
                string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder))
    from pg_type t
    join ns n on n.oid = t.typnamespace
    join pg_enum e on e.enumtypid = t.oid
   group by n.nspname, t.typname
),
funciones as (
  select 40, (n.nspname || '.' || p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')')::text,
         pg_get_functiondef(p.oid) || ';'
    from pg_proc p
    join ns n on n.oid = p.pronamespace
   where p.prokind in ('f', 'p')
     and not exists (select 1 from pg_depend d
                      where d.classid = 'pg_proc'::regclass and d.objid = p.oid and d.deptype = 'e')
),
secuencias as (
  select 45, c.relname::text, format('create sequence if not exists %I.%I;', n.nspname, c.relname)
    from pg_class c
    join ns n on n.oid = c.relnamespace
   where c.relkind = 'S'
     and not exists (select 1 from pg_depend d
                      where d.classid = 'pg_class'::regclass and d.objid = c.oid and d.deptype = 'i')
),
tablas as (
  select 50, c.relname::text,
         format(E'create table %I.%I (\n%s\n);', n.nspname, c.relname,
                string_agg(
                  format('  %I %s', a.attname, format_type(a.atttypid, a.atttypmod))
                  || case a.attidentity when 'a' then ' generated always as identity'
                                        when 'd' then ' generated by default as identity'
                                        else '' end
                  || case when a.attgenerated = 's' then format(' generated always as (%s) stored', pg_get_expr(ad.adbin, ad.adrelid))
                          when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid)
                          else '' end
                  || case when a.attnotnull then ' not null' else '' end,
                  E',\n' order by a.attnum))
    from pg_class c
    join ns n on n.oid = c.relnamespace
    join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
    left join pg_attrdef ad on ad.adrelid = c.oid and ad.adnum = a.attnum
   where c.relkind in ('r', 'p')
   group by n.nspname, c.relname
),
restricciones as (
  -- Las claves foráneas van después de todas las demás: pueden apuntar a
  -- cualquier tabla.
  select case when con.contype = 'f' then 70 else 60 end, (rel.relname || '.' || con.conname)::text,
         format('alter table %I.%I add constraint %I %s;', n.nspname, rel.relname, con.conname, pg_get_constraintdef(con.oid))
    from pg_constraint con
    join pg_class rel on rel.oid = con.conrelid
    join ns n on n.oid = rel.relnamespace
   where con.contype in ('p', 'u', 'c', 'f', 'x')
),
indices as (
  select 80, i.relname::text, pg_get_indexdef(i.oid) || ';'
    from pg_index x
    join pg_class i on i.oid = x.indexrelid
    join pg_class t on t.oid = x.indrelid
    join ns n on n.oid = t.relnamespace
   where not exists (select 1 from pg_constraint con where con.conindid = x.indexrelid)
),
vistas as (
  select 90, c.relname::text,
         format(E'create or replace view %I.%I%s as\n%s', n.nspname, c.relname,
                case when c.reloptions is not null then ' with (' || array_to_string(c.reloptions, ', ') || ')' else '' end,
                pg_get_viewdef(c.oid, true))
    from pg_class c
    join ns n on n.oid = c.relnamespace
   where c.relkind = 'v'
),
disparadores as (
  -- También los de otros esquemas que llaman a funciones propias
  -- (p. ej. `al_crear_usuario` en auth.users → public.crear_perfil).
  select 100, (t.tgrelid::regclass::text || '.' || t.tgname)::text, pg_get_triggerdef(t.oid, true) || ';'
    from pg_trigger t
    join pg_class c on c.oid = t.tgrelid
   where not t.tgisinternal
     and (c.relnamespace in (select oid from ns)
          or t.tgfoid in (select p.oid from pg_proc p where p.pronamespace in (select oid from ns)))
),
rls as (
  select 110, c.relname::text,
         format('alter table %I.%I enable row level security;', n.nspname, c.relname)
         || case when c.relforcerowsecurity
                 then format(E'\nalter table %I.%I force row level security;', n.nspname, c.relname)
                 else '' end
    from pg_class c
    join ns n on n.oid = c.relnamespace
   where c.relkind in ('r', 'p') and c.relrowsecurity
),
politicas as (
  select 120, (p.tablename || '.' || p.policyname)::text,
         format('create policy %I on %I.%I as %s for %s to %s%s%s;',
                p.policyname, p.schemaname, p.tablename, lower(p.permissive), lower(p.cmd),
                array_to_string(p.roles, ', '),
                case when p.qual is not null then E'\n  using (' || p.qual || ')' else '' end,
                case when p.with_check is not null then E'\n  with check (' || p.with_check || ')' else '' end)
    from pg_policies p
   where p.schemaname in (select nspname from ns)
),
permisos_tablas as (
  select 130, c.relname::text,
         format('revoke all on table %I.%I from anon, authenticated;', n.nspname, c.relname)
         || coalesce((
              select string_agg(format(E'\ngrant %s on table %I.%I to %I;', x.privs, n.nspname, c.relname, x.rol), '' order by x.rol)
                from (select r.rolname as rol, string_agg(lower(a.privilege_type), ', ' order by a.privilege_type) as privs
                        from aclexplode(c.relacl) a
                        join pg_roles r on r.oid = a.grantee
                       where r.rolname in ('anon', 'authenticated')
                       group by r.rolname) x), '')
    from pg_class c
    join ns n on n.oid = c.relnamespace
   where c.relkind in ('r', 'p', 'v')
),
permisos_funciones as (
  select 140, (n.nspname || '.' || p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')')::text,
         format('revoke all on function %I.%I(%s) from public, anon, authenticated;',
                n.nspname, p.proname, pg_get_function_identity_arguments(p.oid))
         || coalesce((
              select string_agg(format(E'\ngrant execute on function %I.%I(%s) to %s;', n.nspname, p.proname,
                                       pg_get_function_identity_arguments(p.oid),
                                       case when a.grantee = 0 then 'public' else quote_ident(r.rolname) end),
                                '' order by a.grantee)
                from aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
                left join pg_roles r on r.oid = a.grantee
               where a.privilege_type = 'EXECUTE'
                 and (a.grantee = 0 or r.rolname in ('anon', 'authenticated'))), '')
    from pg_proc p
    join ns n on n.oid = p.pronamespace
   where p.prokind in ('f', 'p')
     and not exists (select 1 from pg_depend d
                      where d.classid = 'pg_proc'::regclass and d.objid = p.oid and d.deptype = 'e')
),
tareas as (
  select 150, j.jobname::text, format('select cron.schedule(%L, %L, %L);', j.jobname, j.schedule, j.command)
    from cron.job j
),
todo as (
  select * from extensiones
  union all select * from esquemas
  union all select * from tipos
  union all select * from funciones
  union all select * from secuencias
  union all select * from tablas
  union all select * from restricciones
  union all select * from indices
  union all select * from vistas
  union all select * from disparadores
  union all select * from rls
  union all select * from politicas
  union all select * from permisos_tablas
  union all select * from permisos_funciones
  union all select * from tareas
)
select string_agg(ddl, E'\n\n' order by orden, clave) as ddl
  from todo;
